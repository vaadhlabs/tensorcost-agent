#!/usr/bin/env bash
# =============================================================================
# TensorCost GPU Agent — bare-metal Linux install script
#
# Installs the agent as a systemd service that pulls the Docker image and
# runs it as a persistent container.
#
# Usage (run as root):
#
#   sudo BACKEND_API_URL=https://api.dev.tensorcost.com \
#        TENANT_ID=<uuid> \
#        AGENT_HOSTNAME=<hostname> \
#        AGENT_API_KEY=<key> \
#        AGENT_KEY_ID=<key-id> \
#        AGENT_HMAC_PEPPER=<hex-pepper> \
#        bash install.sh
#
# Optional overrides:
#   AGENT_IMAGE     — Docker image to pull (default: docker.io/rlgocloudera/gpu-usage:latest)
#   NVML_ENABLED    — true | false (default: true here). Collects GPU metrics.
#                     The agent itself defaults this to false, so this script
#                     turns it ON — a GPU agent that reports no GPU data is the
#                     wrong default for a bare-metal GPU box.
#   COMM_MODE       — http | grpc | both (default: http)
#   GRPC_TARGET     — host:port when COMM_MODE=grpc or both
#   GRPC_USE_TLS    — true | false (default: false)
#   LOG_LEVEL       — DEBUG | INFO | WARN | ERROR (default: INFO)
# =============================================================================

set -euo pipefail

# ---------------------------------------------------------------------------
# Defaults
# ---------------------------------------------------------------------------
AGENT_IMAGE="${AGENT_IMAGE:-public.ecr.aws/tensorcost/gpu-agent:latest}"
NVML_ENABLED="${NVML_ENABLED:-true}"
COMM_MODE="${COMM_MODE:-http}"
GRPC_TARGET="${GRPC_TARGET:-}"
GRPC_USE_TLS="${GRPC_USE_TLS:-false}"
LOG_LEVEL="${LOG_LEVEL:-INFO}"
INSTALL_DIR="/etc/tensorcost"
ENV_FILE="${INSTALL_DIR}/agent.env"
SERVICE_NAME="tensorcost-agent"

# ---------------------------------------------------------------------------
# Validate required inputs
# ---------------------------------------------------------------------------
required_vars=(BACKEND_API_URL TENANT_ID AGENT_HOSTNAME AGENT_API_KEY AGENT_KEY_ID AGENT_HMAC_PEPPER)
missing=()
for v in "${required_vars[@]}"; do
  [[ -z "${!v:-}" ]] && missing+=("$v")
done
if [[ ${#missing[@]} -gt 0 ]]; then
  echo "ERROR: missing required environment variables: ${missing[*]}"
  echo ""
  echo "These come from the TensorCost onboarding wizard. Provision an agent"
  echo "server-side first, then paste the emitted env block before re-running."
  exit 1
fi

# ---------------------------------------------------------------------------
# Check prerequisites
# ---------------------------------------------------------------------------
if [[ $EUID -ne 0 ]]; then
  echo "ERROR: this script must be run as root (sudo)."
  exit 1
fi

for cmd in docker systemctl; do
  if ! command -v "$cmd" &>/dev/null; then
    echo "ERROR: '$cmd' not found. Install it before continuing."
    exit 1
  fi
done

if ! docker info &>/dev/null; then
  echo "ERROR: Docker daemon is not running. Start it first."
  exit 1
fi

# Warn if NVIDIA toolkit is not set up — the container will start but GPU
# access will fail silently.
if ! docker run --rm --gpus all nvidia/cuda:12.0-base-ubuntu22.04 nvidia-smi &>/dev/null 2>&1; then
  echo "WARNING: --gpus all test failed. Make sure 'nvidia-container-toolkit' is installed"
  echo "         and the Docker daemon has been restarted after toolkit installation."
  echo "         The agent will start but will not see any GPUs."
  echo ""
fi

# ---------------------------------------------------------------------------
# Write env file (root-only read permissions — it contains secrets)
# ---------------------------------------------------------------------------
echo "Creating ${ENV_FILE} ..."
mkdir -p "$INSTALL_DIR"
chmod 700 "$INSTALL_DIR"

cat > "$ENV_FILE" <<EOF
# TensorCost GPU Agent — configuration
# Generated by install.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)

BACKEND_API_URL=${BACKEND_API_URL}
TENANT_ID=${TENANT_ID}
AGENT_HOSTNAME=${AGENT_HOSTNAME}
AGENT_API_KEY=${AGENT_API_KEY}
AGENT_KEY_ID=${AGENT_KEY_ID}
AGENT_HMAC_PEPPER=${AGENT_HMAC_PEPPER}

NVML_ENABLED=${NVML_ENABLED}
COMM_MODE=${COMM_MODE}
GRPC_TARGET=${GRPC_TARGET}
GRPC_USE_TLS=${GRPC_USE_TLS}
LOG_LEVEL=${LOG_LEVEL}
EOF

chmod 600 "$ENV_FILE"

# ---------------------------------------------------------------------------
# Pull the image
# ---------------------------------------------------------------------------
echo "Pulling ${AGENT_IMAGE} ..."
docker pull "$AGENT_IMAGE"

# ---------------------------------------------------------------------------
# Write the systemd unit from the template (substituting the image)
# ---------------------------------------------------------------------------
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
UNIT_SRC="${SCRIPT_DIR}/tensorcost-agent.service"
UNIT_DEST="/etc/systemd/system/${SERVICE_NAME}.service"

if [[ ! -f "$UNIT_SRC" ]]; then
  echo "ERROR: unit template not found at ${UNIT_SRC}"
  exit 1
fi

sed "s|AGENT_IMAGE_PLACEHOLDER|${AGENT_IMAGE}|g" "$UNIT_SRC" > "$UNIT_DEST"
chmod 644 "$UNIT_DEST"

# ---------------------------------------------------------------------------
# Enable and start the service
# ---------------------------------------------------------------------------
echo "Enabling and starting ${SERVICE_NAME} ..."
systemctl daemon-reload
systemctl enable "$SERVICE_NAME"
systemctl restart "$SERVICE_NAME"

# Give the container a moment to settle, then show status.
sleep 3
systemctl status "$SERVICE_NAME" --no-pager || true

echo ""
echo "Install complete."
echo ""
echo "Useful commands:"
echo "  journalctl -u ${SERVICE_NAME} -f          # follow logs"
echo "  systemctl status ${SERVICE_NAME}           # service status"
echo "  systemctl restart ${SERVICE_NAME}          # restart after config change"
echo "  systemctl disable ${SERVICE_NAME} --now    # stop and disable"
echo ""
echo "The agent should appear in the TensorCost GPU dashboard within ~2 minutes"
echo "of its first successful heartbeat."
